    progress = st.slider("Орындалған қадамдар саны:", 0, 10, 0)
    st.write(зі := f"Қазіргі деңгей: {progress} / 10 қадам орындалды.")
    
    if st.button("Практиканы аяқтау және бағалау"):
        st.balloons()
        st.success(f"Сіз бұл тапсырмадан {progress} ұпай жинадыңыз!")
